/**
 * Audit blog posts for taxonomy mapping into /industries and /services.
 * Writes docs/seo/content-link-audit.md
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createJiti } from "jiti";

const root = process.cwd();
const jiti = createJiti(join(root, "scripts/backfill-content-links.mjs"), {
  interopDefault: true,
  alias: { "@": root },
});

const postsMod = jiti(join(root, "lib/posts/index.ts"));
const taxonomyMod = jiti(join(root, "content/taxonomy.ts"));

const posts = postsMod.getAllPosts();
const resolveRelatedPillars = taxonomyMod.resolveRelatedPillars;

const PRIORITY_TAGS = new Set([
  "offline-conversions",
  "google-ads",
  "travel",
  "legal",
  "attribution",
  "call-tracking",
  "crm",
]);

function priorityScore(post) {
  let score = 0;
  if (postsMod.hasBody(post)) score += 100;
  for (const tag of post.tags ?? []) {
    if (PRIORITY_TAGS.has(tag)) score += 10;
  }
  score += new Date(post.date).getTime() / 1e12;
  return score;
}

const rows = posts.map((post) => {
  const tags = post.tags ?? [];
  const links = resolveRelatedPillars(tags);
  return {
    slug: post.slug,
    title: post.title,
    date: post.date,
    hasBody: postsMod.hasBody(post),
    tags,
    mapped: links.length > 0,
    linkCount: links.length,
    links,
    score: priorityScore(post),
  };
});

const total = rows.length;
const mapped = rows.filter((r) => r.mapped).length;
const unmapped = rows.filter((r) => !r.mapped);
const withBody = rows.filter((r) => r.hasBody);
const withBodyUnmappedOrWeak = rows
  .filter((r) => r.hasBody && r.linkCount < 2)
  .sort((a, b) => b.score - a.score);

const topPriority = [...rows]
  .sort((a, b) => b.score - a.score)
  .slice(0, 20);

const report = `# Content link audit (Wave 4D)

Generated by \`npm run seo:content-links\` (\`scripts/backfill-content-links.mjs\`).

## Summary

| Metric | Count |
| --- | ---: |
| Total articles | ${total} |
| Mapped to at least one pillar | ${mapped} |
| Unmapped | ${unmapped.length} |
| Articles with body HTML | ${withBody.length} |
| Bodies with fewer than 2 pillar links | ${withBodyUnmappedOrWeak.length} |

## Traffic note

No Search Console export was available in the repo at generation time. The "highest priority" list below is a **traffic proxy**, not measured sessions:

1. Prefer articles that already have a body (indexable).
2. Prefer tags tied to money topics (offline conversions, Google Ads, travel, legal, attribution, call tracking, CRM).
3. Prefer newer dates as a weak tie-breaker.

Replace this proxy with GSC landing-page clicks when \`docs/seo/CONFIG.md\` points at an export.

## Unmapped articles

${
  unmapped.length === 0
    ? "_None. Every frontmatter row resolved at least one pillar._"
    : unmapped
        .map((r) => `- \`${r.slug}\` (tags: ${r.tags.join(", ") || "none"})`)
        .join("\n")
}

## Twenty highest-priority articles (traffic proxy)

These are the articles most likely to waste internal equity if they do not surface pillar links. RelatedServices now renders from tags; verify on each URL that the section appears.

| # | Slug | Body | Tags | Pillar links |
| --- | --- | --- | --- | ---: |
${topPriority
  .map(
    (r, i) =>
      `| ${i + 1} | \`${r.slug}\` | ${r.hasBody ? "yes" : "no"} | ${r.tags.join(", ") || "none"} | ${r.linkCount} |`,
  )
  .join("\n")}

## Tag assignment backfill

Tags were assigned in \`lib/posts/index.ts\` from title and topic. Article HTML bodies were not rewritten. The n8n pipeline should start emitting tags on new posts so this map stays current.

## Recommendations

1. Supply a Search Console landing-page export and re-run this script with click-weighted ranking.
2. Ensure the content pipeline writes \`tags\` into post frontmatter for every new article.
3. Add taxonomy rows when a new vertical or service cluster appears repeatedly in titles.
`;

const outPath = join(root, "docs/seo/content-link-audit.md");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, report, "utf8");

console.log(`Wrote ${outPath}`);
console.log(
  JSON.stringify(
    { total, mapped, unmapped: unmapped.length, withBody: withBody.length },
    null,
    2,
  ),
);
